import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const { build } = createRequire(import.meta.resolve('vite'))('esbuild');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'japan-perfume-'));
try {
  const bundle = path.join(dir, 'test.mjs');
  await build({stdin:{contents:`export * from "./src/utils/perfumePlan2027";
    export { candidateZonePlacesForDay } from "./src/utils/itineraryIntelligence";
    export { selectedBookableReservations } from "./src/utils/reservations";
    export { activityEstimate } from "./src/utils/money";
    export { buildDayRoute } from "./src/utils/route";
    export { loadInitialState } from "./src/hooks/useTripStore";
    export { captureActivityBlackBox } from "./src/utils/activityBlackBox";`,resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',outfile:bundle});
  const m = await import(pathToFileURL(bundle));
  const initial = JSON.parse(fs.readFileSync('src/data/recoveryTrip.json','utf8'));
  const birthday = s => Object.fromEntries(['days','activities','reservations','costs','routeSegments','zonePlaces'].map(k=>[k,s[k].filter(x=>[x.dayId,x.travelDate,x.date,x.suggestedDayId,x.id].includes('2027-01-07'))]));
  initial.activities[0].note = 'Live user note';
  initial.purchases.push({...initial.purchases[0],id:'live-receipt',confirmationNumber:'KEEP'});
  initial.activities.find(a=>a.id==='v7-5-perfume').included=false;
  const before = structuredClone(initial);
  const result = m.applyPerfumePlan2027(initial);
  assert.deepEqual(initial,before,'input must be immutable');
  assert.deepEqual(birthday(result),birthday(before),'entire birthday data must remain unchanged');
  assert.deepEqual(m.candidateZonePlacesForDay(result,'2027-01-07'),m.candidateZonePlacesForDay(before,'2027-01-07'),'birthday suggestions unchanged');
  assert.deepEqual(result.purchases,before.purchases,'receipts and purchases untouched');
  assert.equal(result.activities[0].note,'Live user note');
  const activity = result.activities.find(a=>a.id==='v7-5-perfume');
  assert.equal(activity.included,false,'do not change live selection');
  assert.equal(activity.status,'pendiente_de_reservar');
  assert.equal(activity.start,'11:00'); assert.equal(activity.end,'13:00');
  assert.equal(activity.lat,null,'do not retain Omotesando coordinates');
  const estimate=Math.round(34000*initial.settings.fx.JPY);
  assert.equal(m.activityEstimate(activity,result),estimate);
  assert.equal(result.costs.find(c=>c.id==='d5-perfume').original.quantity,2);
  assert.equal(result.costs.find(c=>c.id==='d5-perfume').estimateCOP,estimate);
  assert.deepEqual(m.applyPerfumePlan2027(result),result,'migration idempotent');
  const edited=structuredClone(result); edited.activities.find(a=>a.id===activity.id).note='Later live edit';
  edited.zonePlaces=edited.zonePlaces.filter(p=>p.id!=='perfume-option-kitowa');
  assert.deepEqual(m.applyPerfumePlan2027(edited),edited,'marker protects later edits and deletions');
  for(const option of m.PERFUME_OPTIONS) {
    const p=result.zonePlaces.find(p=>p.id===`perfume-option-${option.id}`);
    assert.equal(p.selected,false); assert.ok(p.officialUrl.startsWith('https://'));
    assert.ok(p.address); assert.ok(p.sourceIds.every(id=>result.sources.some(s=>s.id===id)));
    for(const day of option.days) assert.ok(m.candidateZonePlacesForDay(result,day).some(x=>x.id===p.id),`${p.title} visible on ${day}`);
    for(const day of ['2027-01-01','2027-01-04','2027-01-07','2027-01-09']) assert.ok(!m.candidateZonePlacesForDay(result,day).some(x=>x.id===p.id));
  }
  activity.included=true;
  const reservation=m.selectedBookableReservations(result).find(r=>r.activityId===activity.id);
  assert.equal(reservation.estimatedPriceCOP,estimate);
  assert.ok(reservation.link.includes('select-type.com')); assert.equal(reservation.bookingCheckDate,undefined);
  assert.ok(!/14 días|22 dic/.test(reservation.opens+reservation.reminderNotes));
  const route=m.buildDayRoute(activity.dayId,null,[activity,...result.activities.filter(a=>a.dayId===activity.dayId&&a.id!==activity.id)],[],result.routeSegments);
  assert.ok(route.points.some(p=>p.title.includes('LIBERTA')));
  assert.ok(route.segments.every(s=>!s.googleMapsUrl.includes('Atelier')));
  const values=new Map(); globalThis.localStorage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
  const fresh=m.loadInitialState();
  assert.ok(fresh.activities.find(a=>a.id===activity.id).title.includes('LIBERTA'));
  const picked=fresh.zonePlaces.find(p=>p.id==='perfume-option-sholayered'); picked.selected=true; picked.suggestedDayId='2027-01-05';
  fresh.activities.find(a=>a.id===activity.id).note='Later live edit';
  fresh.activityBlackBox=m.captureActivityBlackBox(fresh); fresh.activityBlackBox.updatedAt='2026-10-17T23:00:00.000Z';
  values.set('japan-trip-2026-2027-state-v1',JSON.stringify(fresh));
  values.set('japan-trip-2026-2027-recovery-baseline','protected-124-2026-09-27');
  const reloaded=m.loadInitialState();
  assert.equal(reloaded.activities.find(a=>a.id===activity.id).note,'Later live edit');
  assert.equal(reloaded.zonePlaces.find(p=>p.id===picked.id).selected,true);
  assert.ok(!m.candidateZonePlacesForDay(reloaded,'2027-01-05').some(p=>p.id===picked.id),'selection disappears from suggestions');
  assert.equal(reloaded.activityBlackBox.updatedAt,fresh.activityBlackBox.updatedAt,'migration cannot masquerade as a newer live decision');
  console.log(`Perfume integration passed: ${m.PERFUME_OPTIONS.length} verified optional locations; pending LIBERTA, cost for two, routes, Jan 7 unchanged, live edits/receipts, idempotence, selection/reload.`);
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
