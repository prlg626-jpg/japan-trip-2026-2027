import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const { build } = createRequire(import.meta.resolve('vite'))('esbuild');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'japan-payments-'));
try {
  const out = path.join(dir,'check.mjs');
  await build({stdin:{contents:`export * from './src/utils/confirmedNovemberPayments2026'; export {loadInitialState} from './src/hooks/useTripStore'; export {captureActivityBlackBox} from './src/utils/activityBlackBox'; export {purchaseComparison} from './src/utils/purchaseComparison'; export {calculateBudget} from './src/utils/money'; export {selectedBookableReservations} from './src/utils/reservations';`,resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',outfile:out});
  const m = await import(pathToFileURL(out));
  const values = new Map(); globalThis.localStorage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
  const fresh=m.loadInitialState();
  const rows=fresh.purchases.filter(p=>m.NOVEMBER_PAID_ACTIVITIES.includes(p.activityId));
  assert.equal(rows.length,4); assert.ok(rows.every(p=>p.status==='Pagado' && p.paymentMethodLabel.endsWith('2724')));
  assert.equal(rows.filter(p=>p.currency==='EUR').reduce((s,p)=>s+p.originalAmount,0),214.04);
  assert.equal(rows.find(p=>p.activityId==='d25-shink').originalAmount,39180);
  assert.equal(rows.find(p=>p.activityId==='d25-shink').category,'Transporte');
  assert.equal(rows.find(p=>p.activityId==='d7-spa').originalAmount,74000);
  assert.equal(fresh.activities.find(a=>a.id==='d7-spa').start,'16:00');
  assert.equal(fresh.activities.find(a=>a.id==='d25-shink').end,'19:06');
  assert.equal(fresh.activities.find(a=>a.id==='v7-6-ring').included,false);
  assert.ok(!fresh.purchases.some(p=>p.activityId==='v7-6-ring'));
  assert.ok(!m.selectedBookableReservations(fresh).some(r=>m.NOVEMBER_PAID_ACTIVITIES.includes(r.activityId)||r.activityId==='v7-6-ring'));
  assert.equal(m.purchaseComparison(rows).activities.length,3,'train stays in transport, outside activity comparison');
  const edited=structuredClone(fresh);
  edited.purchases.find(p=>p.activityId==='d7-spa').amountCOP=1234567;
  edited.activities.find(a=>a.id==='v7-3-kintsugi').note='Later user edit';
  edited.activityBlackBox=m.captureActivityBlackBox(edited);
  values.set('japan-trip-2026-2027-state-v1',JSON.stringify(edited));
  values.set('japan-trip-2026-2027-recovery-baseline','protected-124-2026-09-27');
  const reloaded=m.loadInitialState();
  assert.equal(reloaded.purchases.filter(p=>m.NOVEMBER_PAID_ACTIVITIES.includes(p.activityId)).length,4,'reload cannot duplicate payments');
  assert.equal(reloaded.purchases.find(p=>p.activityId==='d7-spa').amountCOP,1234567,'bank correction survives');
  assert.equal(reloaded.activities.find(a=>a.id==='v7-3-kintsugi').note,'Later user edit');
  assert.equal(reloaded.activities.find(a=>a.id==='d7-spa').priceOriginal.unit,74000,'pricing cleanup cannot restore old 90min estimate');
  assert.equal(reloaded.activities.find(a=>a.id==='v7-6-ring').included,false,'ring remains deselected');
  assert.equal(reloaded.activities.find(a=>a.id==='d25-shink').priceOriginal.unit,39180);
  assert.equal(m.applyConfirmedNovemberPayments(reloaded).migrated,false);
  const budget=m.calculateBudget(fresh);
  console.log(JSON.stringify({payments:rows.map(({name,originalAmount,currency,amountCOP})=>({name,originalAmount,currency,amountCOP})),addedPaidCOP:rows.reduce((s,p)=>s+p.amountCOP,0),paidCOP:budget.paid,pendingCOP:budget.pending},null,2));
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
